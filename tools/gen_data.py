#!/usr/bin/env python3
"""
Generates the const data headers used by the Uzebox port of NESert Golfing,
directly from the original NES sources/assets (Brad Smith, CC BY 4.0).

  src/data_slopes.h  slope / normal tables  (same algorithm as build_data.py)
  src/data_gfx.h     1bpp font, title logo, mono sprite masks
  src/data_pal.h     NES palette -> RGB332 and the day/night field sets
  src/data_sfx.h     sound effect scripts (parsed from the NES dgolf.c)

Run from the project root:  python3 tools/gen_data.py
"""
import math, os, re, sys
import PIL.Image as Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src")

def write(name, text):
    with open(os.path.join(SRC, name), "w") as f:
        f.write(text)
    print("wrote", name, len(text), "bytes of source")

HDR = ("// GENERATED by tools/gen_data.py - do not edit.\n"
       "// Derived from NESert Golfing by Brad Smith (CC BY 4.0), https://github.com/bbbradsmith/NESertGolfing\n\n")

def carray(ctype, name, vals, width=12, fmt="%d", prog=True):
    s = "static const %s %s[%d]%s = {\n" % (ctype, name, len(vals), " PROGMEM" if prog else "")
    for i in range(0, len(vals), width):
        s += "\t" + ", ".join(fmt % v for v in vals[i:i+width]) + ",\n"
    return s + "};\n\n"

# ---------------------------------------------------------------- slopes
# Identical to build_data.py of the NES project.
def gen_slopes():
    slopes = [0, 1, 2, 3, 4] + ([0] * 8) + ([1] * 8)   # special values, frequent values
    curve = 4
    remain = 128 - len(slopes)
    for i in range(remain):
        slopes.append(4 * math.pow(i / (remain - 1), curve))
    slopes = slopes + [-x for x in slopes]              # second half is negative
    norms = []
    for i in range(len(slopes)):
        s = slopes[i]
        mag = math.sqrt(s * s + 1)
        norms.append((int(s * 256 / mag), int(-256 / mag)))   # int() truncates toward 0 like Python on the NES
        slopes[i] = int(s * 256)
    assert len(slopes) == 256
    t = HDR + "#include <stdint.h>\n#include \"nesert_pgm.h\"\n\n"
    t += "// 8.8 fixed point slope per pixel, index = floor angle byte (bit 7 = negative)\n"
    t += carray("int16_t", "slope_tab", slopes)
    t += "// unit normal (x,y), 8.8 fixed point\n"
    t += carray("int16_t", "norm_x_tab", [n[0] for n in norms])
    t += carray("int16_t", "norm_y_tab", [n[1] for n in norms])
    write("data_slopes.h", t)

# ---------------------------------------------------------------- gfx
def load_idx(fn, pal):
    im = Image.open(os.path.join(HERE, fn)).convert("RGBA")
    out = []
    for y in range(im.size[1]):
        row = []
        for x in range(im.size[0]):
            p = im.getpixel((x, y))[:3]
            best = min(range(len(pal)), key=lambda i: sum((a - b) ** 2 for a, b in zip(p, pal[i])))
            row.append(best)
        out.append(row)
    return out

def tiles_1bpp(img, count):
    res = []
    for t in range(count):
        tx, ty = (t % 16) * 8, (t // 16) * 8
        for y in range(8):
            b = 0
            for x in range(8):
                b = (b << 1) | (1 if img[ty + y][tx + x] else 0)
            res.append(b)
    return res

def gen_gfx():
    pal1 = [(0, 0, 0), (255, 255, 255)]
    pal2 = [(0, 0, 0), (0x65, 0x66, 0x65), (0xb0, 0xb1, 0xb0), (255, 255, 255)]
    layer1 = load_idx("layer1.png", pal1)      # title logo tiles
    layer2 = load_idx("layer2.png", pal1)      # ASCII font, tile index == character code
    sprite = load_idx("sprite.png", pal2)      # 64 sprite tiles, 3 colour
    font = tiles_1bpp(layer2, 128)
    logo = tiles_1bpp(layer1, 128)

    # Monochrome sprite masks. Default: any non-zero pixel is set.
    masks = []
    for t in range(64):
        tx, ty = (t % 16) * 8, (t // 16) * 8
        rows = []
        for y in range(8):
            b = 0
            for x in range(8):
                v = sprite[ty + y][tx + x]
                if 0x1D <= t <= 0x1F:
                    on = v in (1, 2)          # specular highlight (3) becomes a hole: rolling indicator
                elif 0x10 <= t <= 0x19:
                    on = (v == 3)             # flag cloth is set, numerals are holes
                else:
                    on = v != 0
                b = (b << 1) | (1 if on else 0)
            rows.append(b)
        masks.append(rows)
    # Player identity can't use colour in a monochrome mode: tiles 0x2D-0x2F become
    # ring / ring+dot / ring+cross (0x2C stays the flag pole).
    ring = masks[0x2D][:]
    def setpx(rows, x, y):
        rows[y] |= 0x80 >> x
    # centre of the ball sprite is pixel (3,3)
    dot = ring[:]; setpx(dot, 3, 3)
    cross = ring[:]
    for (x, y) in ((3, 2), (2, 3), (3, 3), (4, 3), (3, 4)):
        setpx(cross, x, y)
    masks[0x2E] = dot
    masks[0x2F] = cross
    flat = [b for m in masks for b in m]

    t = HDR + "#include <stdint.h>\n#include \"nesert_pgm.h\"\n\n"
    t += "// 8 bytes per tile, MSB = leftmost pixel. Index = ASCII code (0x03 = solid block).\n"
    t += carray("uint8_t", "font_tab", font, 16, "0x%02X")
    t += "// Title logo, 8 bytes per tile; the NES nametable references tiles 13-15 and 16-127.\n"
    t += carray("uint8_t", "logo_tab", logo, 16, "0x%02X")
    t += "// Monochrome sprite masks from sprite.png (64 tiles x 8 rows).\n"
    t += carray("uint8_t", "spr_tab", flat, 16, "0x%02X")
    write("data_gfx.h", t)

